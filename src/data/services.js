/** تخصصات الفني من صف قادم من الـ API */
export function tradesOf(e) {
  if (!e) return []
  const raw = Array.isArray(e.trades) ? e.trades : []
  const arr = raw.filter((t) => t && t.cat).map((t) => ({ cat: t.cat, subs: Array.isArray(t.subs) ? t.subs : [] }))
  if (e.job && !arr.some((t) => t.cat === e.job)) arr.unshift({ cat: e.job, subs: [] })
  return arr
}
